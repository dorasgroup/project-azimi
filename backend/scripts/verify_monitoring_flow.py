async def cleanup(marker: str) -> None:
    async with SessionFactory() as session:
        user = await session.scalar(select(User).where(User.username == marker))
        if user:
            await session.execute(
                delete(MonitoringJob).where(MonitoringJob.requested_by == user.id)
            )
            await session.execute(delete(Source).where(Source.created_by == user.id))
            await session.execute(delete(BotIdentity).where(BotIdentity.created_by == user.id))
            await session.delete(user)
            await session.commit()


async def create_verification_job(marker: str) -> str:
    async with SessionFactory() as session:
        user = User(
            full_name="Monitoring Flow Verification",
            username=marker,
            email=f"{marker}@example.test",
            password_hash="not-a-real-password-hash",
            role=UserRole.SUPER_ADMIN,
        )
        identity = BotIdentity(
            title="Monitoring flow identity",
            role_definition="Verify monitoring orchestration",
            creator=user,
        )
        source = Source(
            title="Python Blog",
            base_url="https://blog.python.org",
            type=SourceType.NEWS_SITE,
            crawl_config={
                "crawl_policy": {"max_pages": 3, "max_concurrency": 2, "render_javascript": False},
                "processing_policy": {"min_text_length": 100, "min_matched_score": 0.01},
            },
            creator=user,
        )
        session.add_all([user, identity, source])
        await session.flush()

        payload = MonitoringJobCreate(
            topic="Python",
            date_from_jalali="1405/03/01",
            date_to_jalali="1405/03/17",
            source_ids=[source.id],
            bot_identity_id=identity.id,
        )
        assert payload.date_from_gregorian is not None
        assert payload.date_to_gregorian is not None
        result = await CreateMonitoringJob(SqlAlchemyMonitoringJobRepository(session)).execute(
            MonitoringJobDraft(
                topic=payload.topic,
                description=payload.description,
                date_from_jalali=payload.date_from_jalali,
                date_to_jalali=payload.date_to_jalali,
                date_from_gregorian=payload.date_from_gregorian,
                date_to_gregorian=payload.date_to_gregorian,
                source_ids=payload.source_ids,
                bot_identity_id=payload.bot_identity_id,
                requester_id=user.id,
            )
        )
        await session.commit()
        CeleryMonitoringJobQueue().enqueue(result.id)
        return str(result.id)


async def fetch_job_state(job_id: str) -> tuple[JobStatus, int, int, str | None]:
    async with SessionFactory() as session:
        job = await session.get(MonitoringJob, job_id)
        document_count = await session.scalar(
            select(func.count())
            .select_from(CrawledDocument)
            .where(CrawledDocument.job_id == job_id)
        )
        report_count = await session.scalar(
            select(func.count()).select_from(AnalysisReport).where(AnalysisReport.job_id == job_id)
        )
        assert job is not None
        return job.status, int(document_count or 0), int(report_count or 0), job.error_message


async def verify() -> None:
    marker = f"monitoring-flow-{uuid4()}"
    await cleanup(marker)
    try:
        job_id = await create_verification_job(marker)
        # The task id is generated by Celery, so poll durable database state instead.
        for _ in range(60):
            status, document_count, report_count, message = await fetch_job_state(job_id)
            if status in {JobStatus.COMPLETED, JobStatus.FAILED, JobStatus.CANCELLED}:
                break
            await asyncio.sleep(2)
        else:
            raise AssertionError("Monitoring job did not reach a terminal phase boundary")

        status, document_count, report_count, message = await fetch_job_state(job_id)
        assert document_count >= 1, "Monitoring flow did not persist prepared documents"
        assert status == JobStatus.COMPLETED, (status, message)
        assert report_count == 1, "Monitoring flow did not persist an analysis report"
        print(
            "Monitoring flow verification passed: "
            f"job={job_id}, status={status}, documents={document_count}, reports={report_count}"
        )
    finally:
        await cleanup(marker)


if __name__ == "__main__":
    asyncio.run(verify())
