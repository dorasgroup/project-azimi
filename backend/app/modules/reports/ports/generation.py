"""Reporting orchestration ports; implementations live at the composition root."""

from datetime import datetime
from typing import Protocol
from uuid import UUID

from app.modules.reports.domain.generation import ReportClaim, ReportGenerationInput


class ReportGenerationRepository(Protocol):
    async def claim(self, generation_id: UUID, token: UUID, lease_seconds: int, now: datetime) -> ReportClaim: ...
    async def renew_lease(self, generation_id: UUID, token: UUID, lease_seconds: int, now: datetime) -> bool: ...
    async def load_input(self, generation_id: UUID, token: UUID) -> ReportGenerationInput | None: ...
    async def artifact_metadata(self, generation_id: UUID, token: UUID) -> dict[str, tuple[str, str, int]]: ...
    async def accept_artifact(self, generation_id: UUID, token: UUID, *, export_format: str, storage_key: str, checksum: str, size: int, schema_version: str, template_version: str) -> bool: ...
    async def complete(self, generation_id: UUID, token: UUID, artifact_paths: dict[str, str], *, full_report: dict[str, object], sources: list[dict[str, object]]) -> bool: ...
    async def fail_permanently(self, generation_id: UUID, token: UUID, error_code: str) -> bool: ...
    async def release_for_retry(self, generation_id: UUID, token: UUID) -> bool: ...


class ReportArtifactStore(Protocol):
    def save_content_addressed(self, generation_id: UUID, export_format: str, content: bytes) -> tuple[str, str, int]: ...
    def verify(self, generation_id: UUID, export_format: str, key: str, checksum: str, size: int) -> bool: ...
    def path_for(self, report_id: UUID, export_format: str, filename: str | None = None) -> object: ...
